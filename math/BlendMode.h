#pragma once

namespace KCE
{
/**
 * @brief 描画時のブレンドモードを指定する列挙型
 * 
 * 2D/3Dグラフィックスにおいて、ソースカラーとデスティネーションカラーを
 * どのように合成するかを定義する。各モードは異なる視覚効果を生み出す。
 */
enum class BlendMode
{
	Alpha,        // 通常のアルファブレンド（透明度合成）- 半透明オブジェクトの描画に使用
	Additive,     // 加算合成（明るくなる）- 光やパーティクルエフェクトに最適
	Subtractive,  // 減算合成（暗くなる）- 影やダークエフェクトに使用
	Multiply,     // 乗算合成（色を掛け合わせる）- 影や色調整に使用
	Screen,       // スクリーン合成（明るい部分を強調）- 発光エフェクトに使用
	Darken,       // 比較（暗い方）合成 - 暗い色を優先して表示
	Lighten,      // 比較（明るい方）合成 - 明るい色を優先して表示
	ColorBurn,    // カラーバーン（色を焼き込む）- コントラストを強調
	ColorDodge    // カラードッジ（色を抜く・明るくする）- ハイライト効果に使用
};
} // namespace KCE
