    float progress_ = 0.0f;  ///< 繧｢繝九Γ繝ｼ繧ｷ繝ｧ繝ｳ騾ｲ陦悟ｺｦ・・.0=螳悟・縺ｫ髫繧後※縺・ｋ, 1.0=螳悟・縺ｫ陦ｨ遉ｺ・・

